"""M3-H PC HOST-ONLY integration of real LINK scheduling + M1 policy + M3-A model.

ABSOLUTELY NO HTTP, device, credentials, config, tray, files or OTA.
The only transport admitted is M3-A's in-memory LabTransport. The
simulated ACK/readback is NOT an ESP8266 acceptance or LCD scene.
M3-G's actual FslessMetrics/ArduinoJson HTTP behavior is tested by its
separate source-executing CI; that server is NOT joined to this harness.
"""
from __future__ import annotations

from dataclasses import dataclass
import math
import re
import threading

from link_display_modes import DisplayMode, Signals, decide
from link_mode_tray import passive_link_signals
from shino_link import LinkEngine
from control_contract import Binding, LabTransport, Mode, Session, State

_TX = re.compile(r"[0-9a-f]{32}\Z")


@dataclass(frozen=True)
class Snapshot:
    """All outcomes are HOST-only; no field claims applied firmware state."""
    requested_mode: DisplayMode
    proposed_scene: str
    preview_metrics: bool
    preview_music: bool
    telemetry_state: str
    telemetry_attempts: int
    telemetry_accepted: int
    pending_intent: bool
    control_hold: bool
    simulated_ack_readback: bool
    simulated_reason: str | None


class OwnerPriorityLab:
    """One serialized worker, metrics first, at most one POST per human intent.

    A mode is a LOCAL PREVIEW immediately. It is NEVER an actual device mode,
    even when the M3-A FakeDevice returns a simulated confirmed ACK+readback.
    The one-second next-telemetry guard is a HOST research parameter only.
    """

    def __init__(self, engine: LinkEngine, binding: Binding,
                 transport: LabTransport, *, context_supplier,
                 guard_seconds: float = 1.0):
        if type(engine) is not LinkEngine:
            raise TypeError("real LinkEngine required")
        if type(binding) is not Binding or type(transport) is not LabTransport:
            raise TypeError("M3-A in-memory LabTransport only")
        if transport.host != binding.host or engine.host != binding.host:
            raise ValueError("same explicitly supplied host required")
        if not callable(context_supplier):
            raise TypeError("verified HOST context supplier required")
        if type(guard_seconds) not in (int, float) or not math.isfinite(guard_seconds) or not 0 < guard_seconds < 2:
            raise ValueError("HOST guard must be within (0,2) seconds")
        self._engine = engine
        self._binding = binding
        self._transport = transport
        self._context = context_supplier
        self._guard = float(guard_seconds)
        self._lock = threading.Lock()
        self._mode = DisplayMode.AUTO
        self._pending: tuple[DisplayMode, str] | None = None
        self._ever_used_tx: set[str] = set()
        self._hold = False
        self._outcome = None

    def click(self, mode: DisplayMode, transaction: str) -> None:
        """One explicit manual action; never generated by playback/clock.

        Reject racing clicks while pending or in HOLD. Returning to AUTO
        explicitly requires a new, fresh transaction and available gate.
        """
        if type(mode) is not DisplayMode:
            raise TypeError("mode must be DisplayMode")
        if type(transaction) is not str or not _TX.fullmatch(transaction) or not any(c != "0" for c in transaction):
            raise ValueError("fresh 32 lowercase-hex transaction required")
        with self._lock:
            if self._pending or self._hold:
                raise RuntimeError("intent pending or unresolved HOLD")
            if transaction in self._ever_used_tx:
                raise ValueError("transaction reuse forbidden")
            self._ever_used_tx.add(transaction)
            self._mode = mode
            self._pending = (mode, transaction)
            self._outcome = None

    def tick(self, now: float) -> str:
        """Actual LinkEngine.step() always gets its due slot ahead of M3 lab.

        This is ONE deterministic single-thread HOST step. It does not verify
        real Digest mutex acquisition, clock publisher preemption, SDK timing
        or end-to-end traffic on the owner network.
        """
        if type(now) not in (float, int) or not math.isfinite(now) or now < 0:
            raise ValueError("finite monotonic timestamp required")
        with self._lock:
            if now >= self._engine.next_due:
                self._engine.step(float(now))
            if self._pending is None or self._hold:
                return "METRICS_FIRST_NO_CONTROL"
            age = self._engine.observe_success_age(float(now))
            if (self._engine.last_success is None or
                    age is None or age > 6000 or
                    self._engine.state != "CONNECTED" or
                    self._engine.next_due - now <= self._guard):
                # Not a retry or an HTTP attempt. Keep the original click
                # pending until a later safe slot; never invent LINK health.
                return "MODE_PENDING_METRICS_PRIORITY"
            mode, transaction = self._pending
            self._pending = None  # consume before simulated transport call.
            try:
                result = Session(self._binding, self._transport).execute(
                    Mode(mode.value), transaction)
            except (OSError, ValueError, RuntimeError) as exc:
                # Any unexpected exception is terminal HOLD, not an automatic
                # second POST. Never include credentials or request bytes.
                self._hold = True
                self._outcome = ("HOST_EXCEPTION_" + type(exc).__name__, False)
                return "MODE_LAB_HOLD"
            self._outcome = (result.reason, result.state is State.CONFIRMED)
            if result.state is not State.CONFIRMED:
                self._hold = True
                return "MODE_LAB_HOLD"
            return "MODE_ACK_READBACK_SIMULATED_ONLY"

    def snapshot(self) -> Snapshot:
        with self._lock:
            local = passive_link_signals(self._engine, ttl_ms=6000)
            supplied = self._context()
            if type(supplied) is not Signals:
                raise TypeError("context supplier must return validated Signals")
            # Never infer Windows/clock/weather/media freshness from the
            # telemetry ACK: those are separate validated HOST inputs.
            signals = Signals(
                pc_connected=local.pc_connected,
                metrics_fresh=local.metrics_fresh,
                music_playing=supplied.music_playing,
                time_valid=supplied.time_valid,
                weather_valid=supplied.weather_valid,
            )
            result = decide(self._mode, signals)
            return Snapshot(
                requested_mode=self._mode,
                proposed_scene=result.proposed_scene.value,
                preview_metrics=result.show_live_metrics,
                preview_music=result.show_live_music,
                telemetry_state=self._engine.state,
                telemetry_attempts=self._engine.attempts,
                telemetry_accepted=self._engine.accepted,
                pending_intent=self._pending is not None,
                control_hold=self._hold,
                simulated_ack_readback=(self._outcome is not None and self._outcome[1]),
                simulated_reason=self._outcome[0] if self._outcome else None,
            )

    def read_only_reconcile_for_lab(self):
        """No permission to clear HOLD and no POST; may inspect model only."""
        with self._lock:
            if not self._hold:
                return None
            # M3-A transport only, no network and no permissions changed.
            return self._transport.get_status()

