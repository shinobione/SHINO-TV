def resources(sections: Path, stack: Path) -> dict:
    sizes={}
    for line in sections.read_text(encoding="utf-8-sig").splitlines():
        parts=line.split()
        if len(parts)==3 and parts[0].startswith('.') and parts[1].isdigit():
            sizes[parts[0]]=int(parts[1])
    ram=sum(sizes[x] for x in ('.data','.rodata','.bss'))
    flash=sum(sizes[x] for x in ('.data','.rodata','.text','.text1','.irom0.text'))
    assert ram + sizes['.noinit'] <= 40340 + 1024, 'Static RAM exceeds reviewed delta budget'
    frames={}
    for line in stack.read_text(encoding="utf-8-sig").splitlines():
        fields=line.split('\t')
        if len(fields)!=3: continue
        for name in ('checkPayloads()', 'M9LittleFsMountProbe::begin()', 'M9LittleFsMountProbe::json('):
            if name in fields[0]:frames[name]=int(fields[1])
    assert len(frames)==3 and max(frames.values())<=768, 'Unreviewed probe stack-frame growth'
    return {'static_ram_bytes':ram,'noinit_bytes':sizes['.noinit'],'linked_flash_bytes':flash,
            'static_ram_delta_vs_historical_stage1':ram-40340, 'probe_stack_frames_bytes':frames,
            'stack_call_chain_or_physical_high_water_proven':False,'stream_buffer_bytes':256,
            'status_buffer_bytes':768,'payload_bytes':181402}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate-manifest",action="store_true")
    parser.add_argument("--core-root",type=Path)
    parser.add_argument("--symbols",type=Path)
    parser.add_argument("--candidate",type=Path)
    parser.add_argument("--sections",type=Path)
    parser.add_argument("--stack-usage",type=Path)
    args = parser.parse_args()
    if args.generate_manifest: HEADER.write_text(manifest_header(),encoding="utf-8")
    if bool(args.symbols) != bool(args.candidate): parser.error("symbols/candidate required together")
    if bool(args.sections) != bool(args.stack_usage): parser.error("sections/stack-usage required together")
    report = source_gate()
    if args.core_root: report["core"] = core_gate(args.core_root)
    if args.symbols: report["build"] = build_gate(args.symbols,args.candidate)
    if args.sections: report["resources"] = resources(args.sections,args.stack_usage)
    report["future_packet"] = future_packet()
    print(json.dumps(report,indent=2,sort_keys=True))
    return 0

if __name__ == "__main__": raise SystemExit(main())
